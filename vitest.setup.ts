import "@testing-library/jest-dom/vitest";
import { vi } from "vitest";

// jsdom n'implémente pas matchMedia — polyfill minimal pour que le
// ThemeProvider (system via prefers-color-scheme) soit testable.
if (!window.matchMedia) {
  window.matchMedia = vi.fn().mockImplementation((query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: vi.fn(),
    removeListener: vi.fn(),
    addEventListener: vi.fn(),
    removeEventListener: vi.fn(),
    dispatchEvent: vi.fn(),
  }));
}

// Le global `localStorage` expérimental de Node (backé par un fichier) peut
// prendre le pas sur celui de jsdom selon la version de Node — on force un
// stockage mémoire simple et synchrone pour des tests fiables et isolés.
class MemoryStorage implements Storage {
  private store = new Map<string, string>();

  get length() {
    return this.store.size;
  }

  clear() {
    this.store.clear();
  }

  getItem(key: string) {
    return this.store.has(key) ? this.store.get(key)! : null;
  }

  key(index: number) {
    return Array.from(this.store.keys())[index] ?? null;
  }

  removeItem(key: string) {
    this.store.delete(key);
  }

  setItem(key: string, value: string) {
    this.store.set(key, String(value));
  }
}

Object.defineProperty(window, "localStorage", {
  value: new MemoryStorage(),
  writable: true,
});
